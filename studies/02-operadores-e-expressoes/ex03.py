print (f"=============COMPARAÇÕES=============")
print (f"--Compare dois numeros")

numero1 = int(input("Digite o primeiro numero"))
numero2 = int(input("Digite o segundo numero"))

igual = numero1 == numero2
diferente = numero1 != numero2
maior = numero1 > numero2
menor = numero1 < numero2
maior_ou_igual = numero1 >= numero2
menor_ou_igual = numero1 <= numero2

print (f"=============Resultados=============")
print (f"Igual: {igual}")
print (f"Diferente: {diferente}")
print (f"Maior: {maior}")
print (f"Menor: {menor}")
print (f"Maior ou Igual: {maior_ou_igual}")
print (f"Menor ou Igual: {menor_ou_igual}")

print (f"====================================")
